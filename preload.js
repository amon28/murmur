const { contextBridge, ipcRenderer } = require('electron')

const on = (ch) => (fn) => { const h = (_e, v) => fn(v); ipcRenderer.on(ch, h); return () => ipcRenderer.removeListener(ch, h) }

contextBridge.exposeInMainWorld('murmur', {
  chat: {
    send: (text) => ipcRenderer.invoke('chat:send', text),
    stop: () => ipcRenderer.invoke('chat:stop'),
    history: () => ipcRenderer.invoke('chat:history'),
    create: () => ipcRenderer.invoke('chat:new'),
    open: (id) => ipcRenderer.invoke('chat:open', id),
    list: (q) => ipcRenderer.invoke('chat:list', q),
    rename: (id, title) => ipcRenderer.invoke('chat:rename', id, title),
    remove: (id) => ipcRenderer.invoke('chat:delete', id),
    rate: (conv, at, rating) => ipcRenderer.invoke('chat:rate', conv, at, rating),
    branch: (conv, at, k) => ipcRenderer.invoke('chat:branch', conv, at, k),
    onStart: on('chat:start'), onRecall: on('chat:recall'), onNotice: on('chat:notice'), onToken: on('chat:token'), onDone: on('chat:done'), onThink: on('chat:think'), onStatus: on('chat:status'), onListChanged: on('chats-changed'),
  },
  attach: {
    add: (a) => ipcRenderer.invoke('attach:add', a),
    image: (id) => ipcRenderer.invoke('attach:image', id),
    onPushed: on('attach:pushed'), // a screen capture made in the main process
  },
  screen: { capture: () => ipcRenderer.invoke('screen:capture') },
  vad: { start: () => ipcRenderer.invoke('vad:start'), prob: (frame) => ipcRenderer.invoke('vad:prob', frame) },
  type: { text: (t) => ipcRenderer.invoke('type:text', t), state: (on) => ipcRenderer.invoke('type:state', on) },
  changelog: { get: () => ipcRenderer.invoke('changelog:get'), seen: () => ipcRenderer.invoke('changelog:seen'), onShow: on('changelog:show') },
  update: { onReady: on('update:ready'), install: () => ipcRenderer.invoke('update:install') },
  profile: {
    get: () => ipcRenderer.invoke('profile:get'),
    set: (p) => ipcRenderer.invoke('profile:set', p),
    reflect: () => ipcRenderer.invoke('profile:reflect'),
    reset: (what) => ipcRenderer.invoke('profile:reset', what),
    onChanged: on('profile-changed'),
  },
  setup: {
    status: () => ipcRenderer.invoke('setup:status'),
    download: (keys) => ipcRenderer.invoke('setup:download', keys),
    pause: () => ipcRenderer.invoke('setup:pause'),
    onProgress: on('setup:progress'),
  },
  openUrl: (url) => ipcRenderer.invoke('app:openUrl', url),
  previewHtml: (html) => ipcRenderer.invoke('preview:html', html),
  clipboardText: () => ipcRenderer.invoke('app:clipboard'),
  info: () => ipcRenderer.invoke('app:info'),
  ears: { transcribe: (wav) => ipcRenderer.invoke('ears:transcribe', wav), wake: () => ipcRenderer.invoke('ears:wake'), dictating: (on) => ipcRenderer.invoke('ears:dictating', on) },
  notes: {
    list: () => ipcRenderer.invoke('notes:list'),
    get: (id) => ipcRenderer.invoke('notes:get', id),
    create: (n) => ipcRenderer.invoke('notes:create', n),
    update: (n) => ipcRenderer.invoke('notes:update', n),
    remove: (id) => ipcRenderer.invoke('notes:delete', id),
    search: (q) => ipcRenderer.invoke('notes:search', q),
    fromDictation: (t) => ipcRenderer.invoke('notes:fromDictation', t),
    exportAll: () => ipcRenderer.invoke('notes:export'),
    importFiles: () => ipcRenderer.invoke('notes:import'),
    trash: () => ipcRenderer.invoke('notes:trash'),
    restore: (id) => ipcRenderer.invoke('notes:restore', id),
    purge: (id) => ipcRenderer.invoke('notes:purge', id),
    undo: (op) => ipcRenderer.invoke('notes:undo', op),
    ai: (id, action) => ipcRenderer.invoke('notes:ai', id, action),
    onChanged: on('notes-changed'),
    onOpen: on('note:open'),
    onDue: on('note:due'),
  },
  settings: {
    get: () => ipcRenderer.invoke('settings:get'),
    set: (s) => ipcRenderer.invoke('settings:set', s),
    restart: (which) => ipcRenderer.invoke('settings:restart', which),
    pick: (opts) => ipcRenderer.invoke('settings:pick', opts),
    openData: () => ipcRenderer.invoke('app:openData'),
  },
  status: () => ipcRenderer.invoke('status'),
  onStatus: on('status'),
  onDictateHotkey: on('hotkey:dictate'),
  onTypeHotkey: on('hotkey:type'),
  win: { minimize: () => ipcRenderer.invoke('win:minimize'), close: () => ipcRenderer.invoke('win:close'), pin: () => ipcRenderer.invoke('win:pin') },
})
